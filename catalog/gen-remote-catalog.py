#!/usr/bin/env python3
"""
Write the live model list (the file served at
https://goblincorps.com/gobbonet_model_list.json) from catalog/models.ini.

GobboNet prefers that live list and falls back to the bundled models.ini, so
the two should say the same thing. This keeps them in step: launch.bat is the
source of truth, gen-catalog.py turns it into models.ini, and this turns
models.ini into the JSON to upload.

Schema version 1, as internal/catalog/remote.go reads it. Fields an older
client does not know (moe_min_vram_gb, min_ram_gb, tier) are ignored by it,
so min_client stays where it was.

Usage:  python3 catalog/gen-remote-catalog.py [models.ini] [out.json]
        defaults: catalog/models.ini -> catalog/gobbonet_model_list.json
"""

import json
import os
import sys
from collections import OrderedDict
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
MIN_CLIENT = "1.7.0"


def read_ini(path):
    sections, cur = OrderedDict(), None
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line[0] in ";#":
                continue
            if line.startswith("[") and line.endswith("]"):
                cur = sections.setdefault(line[1:-1], OrderedDict())
                continue
            if cur is not None and "=" in line:
                k, v = line.split("=", 1)
                cur[k.strip()] = v.strip()
    return sections


def tier(entry):
    """The same rule as Entry.Tier in internal/catalog: MoE first, then by VRAM."""
    if entry.get("moe_min_vram") and entry.get("min_ram"):
        return "moe"
    v = int(entry.get("min_vram") or 0)
    if v <= 8:
        return "small"
    if v <= 16:
        return "mid"
    return "large"


def main(argv):
    src = argv[0] if argv else os.path.join(HERE, "models.ini")
    dst = argv[1] if len(argv) > 1 else os.path.join(HERE, "gobbonet_model_list.json")
    ini = read_ini(src)
    rec = ini.get("recommend", {})
    rungs = []
    for i in range(1, int(rec.get("rungs", 0)) + 1):
        rungs.append({"vram_gb": int(rec["rung%d_vram" % i]), "pick": int(rec["rung%d_pick" % i])})
    models = []
    for name, e in ini.items():
        if not name.isdigit():
            continue
        t = tier(e)
        tags = [x for x in e.get("tags", "").split(",") if x]
        if t == "moe" and "moe" not in tags:
            tags.append("moe")
        m = OrderedDict([
            ("index", int(name)),
            ("display", e.get("display", "")),
            ("repo", e["repo"]),
            ("file", e["file"]),
            ("size_gb", float(e.get("size_gb", 0))),
            ("min_vram_gb", int(e.get("min_vram", 0))),
        ])
        if t == "moe":
            m["moe_min_vram_gb"] = int(e["moe_min_vram"])
            m["min_ram_gb"] = int(e["min_ram"])
        m.update([
            ("tier", t),
            ("ctx", int(e.get("ctx", 0))),
            ("kv", e.get("kv", "q8_0")),
            ("sha256", e.get("sha256") or None),
            ("tags", tags),
            ("chat_template", None),
            ("use_jinja", False),
            ("notes", ""),
        ])
        models.append(m)
    models.sort(key=lambda m: m["index"])
    doc = OrderedDict([
        ("schema_version", 1),
        ("generated", datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")),
        ("min_client", MIN_CLIENT),
        ("_readme", "Served at https://goblincorps.com/gobbonet_model_list.json. Generated by "
                    "catalog/gen-remote-catalog.py from catalog/models.ini; launch.bat remains the "
                    "source of truth for the model set. sha256 is pinned by catalog/pin-hashes.py "
                    "from the HuggingFace LFS oid, so the client has an expected hash that did not "
                    "come from the download host at download time. null means not pinned yet: the "
                    "client marks the entry UNVERIFIED and asks twice."),
        ("recommend", OrderedDict([
            ("headroom_gb", 2),
            ("rungs", rungs),
            ("cpu_only", int(rec.get("cpu_only", 0))),
            ("default", int(rec.get("default", 0))),
        ])),
        ("models", models),
    ])
    pinned = sum(1 for m in models if m["sha256"])
    # Unchanged apart from the timestamp: leave the file as it is, so running
    # this has no diff to review and the served copy's date stays meaningful.
    try:
        with open(dst, encoding="utf-8") as f:
            old = json.load(f, object_pairs_hook=OrderedDict)
        same = dict(old, generated=None) == dict(doc, generated=None)
    except (OSError, ValueError):
        same = False
    if same:
        print("gen-remote-catalog: %s is already current (%d models, %d pinned)" % (dst, len(models), pinned))
        return 0
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=2)
        f.write("\n")
    print("gen-remote-catalog: wrote %s (%d models, %d pinned)" % (dst, len(models), pinned))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
